import { test, expect } from '@playwright/test'

test('tasks persist and support editing, filters, completion, and deletion', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByText('A fresh start, just for you')).toBeVisible()
  await page.getByRole('button', { name: 'Add task', exact: true }).click()
  await page.getByLabel('Task name').fill('Prepare a project brief')
  await page.getByLabel('Notes').fill('Outline the goals and next steps.')
  await page.getByLabel('Project', { exact: true }).selectOption('Work')
  await page.getByLabel('Priority', { exact: true }).selectOption('high')
  await page.getByRole('dialog').getByLabel('Due date').fill('2027-01-15')
  await page.getByRole('dialog').getByRole('button', { name: 'Add task' }).click()
  await expect(page.getByRole('button', { name: 'Edit Prepare a project brief' })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'Edit Prepare a project brief' }).click()
  await expect(page.getByLabel('Notes')).toHaveValue('Outline the goals and next steps.')
  await page.getByLabel('Task name').fill('Share the project brief')
  await page.getByRole('button', { name: 'Save changes' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Edit Share the project brief' })).toBeVisible()
  await page.getByLabel('Search tasks').fill('no match')
  await expect(page.getByText('No matching tasks')).toBeVisible()
  await page.getByRole('button', { name: 'Clear search' }).click()
  await page.getByRole('navigation', { name: 'Projects' }).getByRole('button', { name: /Personal/ }).click()
  await expect(page.getByText('A little breathing room')).toBeVisible()
  await page.getByRole('navigation', { name: 'Projects' }).getByRole('button', { name: /Work/ }).click()
  await page.getByRole('button', { name: 'Complete: Share the project brief', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Mark incomplete: Share the project brief' })).toBeVisible()
  await page.getByRole('button', { name: 'Active', exact: true }).click()
  await expect(page.getByText('A little breathing room')).toBeVisible()
  await page.getByRole('button', { name: 'All', exact: true }).click()
  await page.getByRole('button', { name: 'Mark incomplete: Share the project brief' }).click()
  await expect(page.getByRole('button', { name: 'Complete: Share the project brief', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Delete Share the project brief' }).click()
  await expect(page.getByText('A fresh start, just for you')).toBeVisible()
  expect(errors).toEqual([])
})

test('mobile navigation and dialog fit the viewport', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByText('A fresh start, just for you')).toBeVisible()
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('navigation', { name: 'Task views' }).getByRole('button', { name: /Today/ }).click()
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Make room for today')
  await page.getByRole('button', { name: 'Add task', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/mobile.png', fullPage: true })
})
